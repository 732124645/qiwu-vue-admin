// scripts/codegen-report.mjs against a throwaway git repository: the scaffold commit is found by its
// subject only, and through renames.
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { afterEach, it } from 'vitest'

const script = join(process.cwd(), '../../scripts/codegen-report.mjs')
let repo = ''
afterEach(() => rmSync(repo, { recursive: true, force: true }))
const entity = (table: string): string =>
  `// @generated by qw-codegen (crud)\n@Entity('${table}')\nexport class Row {\n${Array.from(
    { length: 12 },
    (_, i) => `  col${i}!: string\n`,
  ).join('')}}\n`

it('scaffold commit: subject only, renames followed', () => {
  repo = mkdtempSync(join(tmpdir(), 'qw-cg-report-'))
  const git = (...args: string[]): string =>
    execFileSync(
      'git',
      ['-c', 'user.name=t', '-c', 'user.email=t@t', '-c', 'commit.gpgsign=false', ...args],
      { cwd: repo, encoding: 'utf8' },
    ).trim()
  const put = (path: string, text: string): void => {
    mkdirSync(dirname(join(repo, path)), { recursive: true })
    writeFileSync(join(repo, path), text)
  }
  const mod = 'apps/server/src/modules'
  git('init', '-q')
  put('docs/.keep', '')

  // demo/book: scaffolded at biz/demo/book, then moved to demo/book (+1 line) by a commit whose BODY
  // quotes the phrase
  put(`${mod}/biz/demo/book/book.entity.ts`, entity('demo_book'))
  git('add', '.')
  git('commit', '-q', '-m', 'feat(demo/book): scaffold via codegen')
  const scaffold = git('rev-parse', '--short', 'HEAD')
  git('mv', `${mod}/biz/demo`, `${mod}/demo`)
  put(`${mod}/demo/book/book.entity.ts`, `${entity('demo_book')}// edited by hand\n`)
  git('commit', '-q', '-am', 'refactor(repo): move demo\n\nNot a scaffold via codegen commit.')

  // demo/topic: generated header, but only a body mentions the phrase → no scaffold commit; its entity
  // is similar enough to book's that `git log --follow` sees a copy and would walk into book's history
  put(`${mod}/demo/topic/topic.entity.ts`, entity('demo_topic'))
  git('add', '.')
  git('commit', '-q', '-m', 'feat(demo/topic): by hand\n\nLater: scaffold via codegen.')

  execFileSync('node', [script, repo], { encoding: 'utf8' })
  const rows = readFileSync(join(repo, 'docs/codegen-report.md'), 'utf8')
  const row = (name: string): string[] | undefined =>
    rows
      .split('\n')
      .find((l) => l.startsWith(`| ${name} |`))
      ?.split('|')
      .map((c) => c.trim())
  assert.deepEqual(row('demo/book')?.slice(4, 6), [scaffold, '+1 −0'])
  assert.deepEqual(row('demo/topic')?.slice(4, 6), ['—', ''])
})
