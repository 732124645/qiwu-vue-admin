// `pnpm gen:check-golden` (quality gate; see docs/design-notes.md#codegen): every G0 module in the repository is exactly what
// the generator renders from its committed config. The golden list is the config seeds
// `apps/server/src/db/seeds/codegen/<table>.cg.ts`. Runs on the test database only: the env is
// `.env.test` over git-ignored `.env.local` credentials, then optional git-ignored `.env.test.local`
// (as the server tests load them; never `.env`, the dev database). Only named test DB/Redis pairs
// are accepted before the reset. Builds the server (not with `--skip-build`: ci:local's build step
// just did), resets that database (migrate + seed, which stores the configs), renders with the CLI into
// a temp dir and diffs each file (sources, specs, locale fragments)
// against the committed one; the other way round, a committed `@generated` file of a G0 module (in its
// own directories, or at one of its file names) that the generator no longer renders fails too.
// Exit 1 with the diffs; --write explicitly adopts the rendered G0 files after checking every target.
import { execSync, spawnSync } from 'node:child_process'
import {
  existsSync,
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { parseEnv } from 'node:util'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const serverDir = join(root, 'apps/server')
const seedDir = join(serverDir, 'src/db/seeds/codegen')
// the uni-app client: a withMobile module's pages; PC only (no mobile/): the CLI renders none
// there and nothing of it is collected below (docs/mobile.md)
const MOBILE = 'mobile/src/'

const loadEnv = (file) => {
  const path = join(serverDir, file)
  return existsSync(path) ? parseEnv(readFileSync(path, 'utf8')) : {}
}
// the files win over the shell: a DB_NAME exported for dev work must not leak in
const env = {
  ...process.env,
  ...loadEnv('.env.local'),
  ...loadEnv('.env.test'),
  ...loadEnv('.env.test.local'),
  ENV_FILE: '.env.test',
}

/** Runs `cmd`; its output only shows when it fails (then the check fails too). */
function run(what, cmd, args, cwd = serverDir) {
  const r = spawnSync(cmd, args, { cwd, env, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  if (r.status === 0) return
  process.stdout.write(r.stdout ?? '')
  process.stderr.write(r.stderr ?? '')
  throw new Error(`${what} failed (${r.status ?? r.signal ?? r.error?.message})`)
}

/** Files below `dir`, relative, `/`-separated. */
const filesOf = (dir) =>
  readdirSync(dir, { recursive: true })
    .filter((p) => lstatSync(join(dir, p)).isFile())
    .map((p) => p.split('\\').join('/'))
    .sort()

const GENERATED = /^(\/\/|<!--) @generated by qw-codegen /
/**
 * The committed `@generated` files of the modules whose entities `rendered` holds: everything in each
 * module's own directories (server module, web views, mobile pages) and its files in the shared
 * directories (spec, schema, web and mobile api), by the naming of docs/codegen-golden.md.
 */
function generatedScope(rendered) {
  return rendered.flatMap((path) => {
    // home: `<domain>/<biz>` (a project domain) or `<group>/<domain>/<biz>`
    const m = /^apps\/server\/src\/modules\/((?:[^/]+\/)*?([^/]+)\/([^/]+))\/\3\.entity\.ts$/.exec(
      path,
    )
    if (!m) return []
    const [, home, domain, biz] = m
    return [
      {
        entity: path,
        dirs: [dirname(path), `apps/web/src/views/${home}`, `${MOBILE}pages-biz/${home}`],
        files: [
          `apps/server/test/e2e/${domain}-${biz}.e2e-spec.ts`,
          `packages/shared/src/${home}.schema.ts`,
          `apps/web/src/api/${home}.ts`,
          `${MOBILE}api/${home}.ts`,
        ],
        locales: ['zh-CN', 'en-US'].flatMap((lang) => [
          `packages/shared/src/i18n/${lang}/modules/${domain}.${biz}.json`,
          `apps/web/src/locales/${lang}/${domain}.${biz}.json`,
          `${MOBILE}locales/${lang}/${domain}.${biz}.json`,
        ]),
      },
    ]
  })
}

export function committedGenerated(rendered, at = root) {
  const paths = new Set()
  for (const { dirs, files } of generatedScope(rendered)) {
    for (const dir of dirs)
      if (existsSync(join(at, dir)))
        for (const f of filesOf(join(at, dir))) paths.add(`${dir}/${f}`)
    for (const f of files) paths.add(f)
  }
  return [...paths].filter(
    (p) => existsSync(join(at, p)) && GENERATED.test(readFileSync(join(at, p), 'utf8')),
  )
}

/** Compare G0 output; --write validates the entire batch before replacing files or removing stale ones. */
export function syncGolden(out, at, { checkPath, target, diffOf }, write = false) {
  const files = filesOf(out)
  const scope = generatedScope(files)
  if (!scope.length) throw new Error('no G0 entity in rendered output')
  const full = (path) => target(at, checkPath(path, true))
  for (const { entity } of scope) {
    const anchor = full(entity)
    if (write && (!existsSync(anchor) || !GENERATED.test(readFileSync(anchor, 'utf8'))))
      throw new Error(`not an existing G0 module: ${entity}`)
  }
  const contents = new Map()
  for (const path of files) {
    checkPath(path, true)
    if (
      !scope.some(
        ({ dirs, files, locales }) =>
          dirs.some((dir) => path.startsWith(`${dir}/`)) ||
          files.includes(path) ||
          locales.includes(path),
      )
    )
      throw new Error(`not a G0 target: ${path}`)
    contents.set(path, readFileSync(join(out, path)))
  }
  // Keep the existing G0 stale-delete scope: module directories and named spec/schema/api files.
  const stale = committedGenerated(files, at).filter((p) => !contents.has(p))
  const differ = files.filter((path) => {
    const dest = full(path)
    return !existsSync(dest) || !readFileSync(dest).equals(contents.get(path))
  })
  if (!write) {
    for (const path of differ) {
      if (!existsSync(full(path))) console.log(`missing: ${path}`)
      else process.stdout.write(diffOf(full(path), path, contents.get(path).toString('utf8')))
    }
    for (const path of stale) console.log(`stale: ${path}`)
    return { files, differ, stale }
  }

  const paths = [...files, ...stale]
  const git = (args) => {
    const r = spawnSync('git', args, { cwd: at, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
    if (r.error || r.status !== 0)
      throw new Error(`git target check failed: ${r.error?.message ?? r.stderr ?? r.status}`)
    return r.stdout
  }
  const entries = git(['ls-files', '-v', '-z', '--', ...paths])
    .split('\0')
    .filter(Boolean)
  for (const entry of entries)
    if (/^[a-zS] /.test(entry))
      throw new Error(`refused assume-unchanged or skip-worktree target: ${entry.slice(2)}`)
  const tracked = new Set(entries.map((entry) => entry.slice(2)))
  for (const path of paths)
    if (existsSync(full(path)) && !tracked.has(path))
      throw new Error(`refused untracked existing target: ${path}`)
  const dirty = git(['status', '--porcelain=v1', '-z', '--untracked-files=all', '--', ...paths])
  if (dirty)
    throw new Error(`refused dirty targets: ${dirty.split('\0').filter(Boolean).join(', ')}`)

  const touched = []
  const created = []
  try {
    for (const path of differ) {
      const dest = full(path)
      const exists = existsSync(dest)
      mkdirSync(dirname(dest), { recursive: true })
      touched.push(path) // include a file whose replacement failed after removing it
      if (!exists) created.push(path)
      if (exists) rmSync(dest)
      writeFileSync(dest, contents.get(path), { flag: 'wx' })
    }
    for (const path of stale) {
      touched.push(path)
      rmSync(full(path))
    }
  } catch (err) {
    const restore = touched.filter((p) => tracked.has(p))
    throw new Error(
      `write failed: ${err.message}\ntouched paths: ${touched.join(', ') || '(none)'}\n` +
        (restore.length ? `restore tracked files: git checkout -- ${restore.join(' ')}\n` : '') +
        (created.length ? `remove new files if present: ${created.join(', ')}\n` : ''),
    )
  }
  return { files, differ, stale }
}

/** Optional extra test DB/Redis pairs for parallel checkouts; absent file = the default pair only. */
export const testLanes = (file = join(root, 'scripts/test-lanes.private.json')) =>
  existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {}

export const ALLOWED_PAIRS = [['qiwu_test', '15'], ...(testLanes().testPairs ?? [])]

/** Why `env` must not be reset (anything but a named server test DB/Redis pair); null = fine. */
export const refusal = ({ DB_NAME = '', REDIS_DB = '' }, pairs = ALLOWED_PAIRS) =>
  pairs.some(([db, redis]) => DB_NAME === db && REDIS_DB === redis)
    ? null
    : `refused: allowed DB_NAME/REDIS_DB pairs: ${pairs.map(([db, redis]) => `(${db}, ${redis})`).join(', ')}; got ('${DB_NAME}', '${REDIS_DB}')`

async function main() {
  // only named server test databases and their Redis dbs: the reset drops every table
  const refused = refusal(env)
  if (refused) throw new Error(refused)
  const tables = readdirSync(seedDir)
    .filter((f) => f.endsWith('.cg.ts'))
    .map((f) => f.slice(0, -'.cg.ts'.length))
  if (!tables.length) throw new Error(`no golden module: no *.cg.ts in ${seedDir}`)

  // with @qiwu/shared (its dist is what the server build reads)
  if (!process.argv.includes('--skip-build')) {
    try {
      execSync('pnpm --filter @qiwu/server... build', {
        cwd: root,
        env,
        encoding: 'utf8',
        maxBuffer: 64 * 1024 * 1024,
        stdio: ['ignore', 'pipe', 'pipe'],
      })
    } catch (e) {
      process.stdout.write(e.stdout ?? '')
      process.stderr.write(e.stderr ?? '')
      throw new Error(`build failed (${e.status ?? e.signal ?? e.message})`)
    }
  }
  run(`db:reset (${env.DB_NAME})`, process.execPath, ['dist/db/reset.js'])
  const out = mkdtempSync(join(tmpdir(), 'qw-golden-'))
  try {
    const cli = 'dist/modules/platform/codegen/cli.js'
    run('gen render', process.execPath, [cli, 'render', ...tables, '--out', out])
    // Import the built server's guards: no root-script dependency in the deployed workspace module.
    const workspace = await import(
      pathToFileURL(join(serverDir, 'dist/modules/platform/codegen/workspace.js')).href
    )
    const write = process.argv.includes('--write')
    const { files, differ, stale } = syncGolden(out, root, workspace, write)
    const what = `${files.length} file(s) of ${tables.join(', ')}`
    if (write)
      return console.log(
        `gen:check-golden wrote ${differ.length} file(s), removed ${stale.length} stale file(s): ${what}`,
      )
    if (!differ.length && !stale.length)
      return console.log(`gen:check-golden ok: ${what} match the repository`)
    if (differ.length)
      console.error(
        `gen:check-golden FAILED: ${differ.length} of ${what} differ from the repository ` +
          '(diff above: a = committed, b = rendered); fix the templates or the module, never one alone',
      )
    if (stale.length)
      console.error(
        `gen:check-golden FAILED: ${stale.length} committed generated file(s) no longer rendered ` +
          `(${stale.join(', ')}): delete them with the template change`,
      )
    process.exitCode = 1
  } finally {
    rmSync(out, { recursive: true, force: true })
  }
}

// run as a script (the spec imports the helpers above)
if (process.argv[1] === fileURLToPath(import.meta.url))
  try {
    await main()
  } catch (err) {
    console.error(`gen:check-golden: ${err.message}`)
    process.exitCode = 1
  }
